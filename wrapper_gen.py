from rtl_gen import WIDTH, select_width

# Wrapper generator: writes the two files top.v depends on
#   composite_system.v   - connects switches to the generated design and packs every
#                          observable value (final outputs, then each unit) into one bus
#   generated_config.vh  - defines NUM_OBSERVABLES for top.v
# switches: SW[3:0] = input 1, SW[7:4] = input 2, SW[11:8] = input 3, SW[15:12] = input 4
# any other primary inputs are hardcoded to HARDCODED_VALUE

HARDCODED_VALUE = 2


def write_wrapper(plan, dag, module_name, filename, header_filename):
    inputs = dag["inputs"]
    unit_names = list(plan["units"])
    num_units = len(unit_names)
    state_bits = select_width(plan["num_cycles"] + 2)

    # observable names in display order
    # Ex: ["out_S0", "add0", "sub0", "mul0"]
    observables = []
    for name, reg_name in plan["outputs"]:
        observables.append(f"out_{name}")
    for unit_name in unit_names:
        observables.append(unit_name)

    # where each input comes from
    # Ex: B -> ("{12'd0, sw[3:0]}", "sw[3:0]"),  I -> ("16'd2", "hardcoded 2")
    input_wiring = []
    for index in range(len(inputs)):
        if index < 4:
            low = index * 4
            input_wiring.append((inputs[index], f"{{{WIDTH-4}'d0, sw[{low + 3}:{low}]}}", f"sw[{low + 3}:{low}]"))
        else:
            input_wiring.append((inputs[index], f"{WIDTH}'d{HARDCODED_VALUE}", f"hardcoded {HARDCODED_VALUE}"))

    lines = []
    lines.append("`timescale 1ns / 1ps")
    lines.append("// composite_system.v - generated by wrapper_gen.py")
    for name, expression, label in input_wiring:
        lines.append(f"//   {name} = {label}")
    for index in range(len(observables)):
        lines.append(f"//   observable {index} = {observables[index]}")
    lines.append("")
    lines.append("module composite_system (")
    lines.append("    input clk, rst, step_en,")
    lines.append("    input [15:0] sw,")
    lines.append(f"    output [{len(observables) * WIDTH - 1}:0] observables,")
    lines.append("    output [7:0] state")
    lines.append(");")
    lines.append("")
    for name, reg_name in plan["outputs"]:
        lines.append(f"    wire [{WIDTH-1}:0] out_{name};")
    lines.append(f"    wire [{num_units * WIDTH - 1}:0] unit_values;")
    lines.append(f"    wire [{state_bits-1}:0] fsm_state;")
    lines.append("    wire done;")
    lines.append("")

    # start is held high: a step from IDLE or DONE latches the switches and starts a run
    ports = [".clk(clk)", ".rst(rst)", ".en(step_en)", ".start(1'b1)"]
    for name, expression, label in input_wiring:
        ports.append(f".in_{name}({expression})")
    for name, reg_name in plan["outputs"]:
        ports.append(f".out_{name}(out_{name})")
    ports.append(".unit_values(unit_values)")
    ports.append(".state(fsm_state)")
    ports.append(".done(done)")
    lines.append(f"    {module_name} dut (")
    lines.append("        " + ",\n        ".join(ports))
    lines.append("    );")
    lines.append("")

    # observable 0 goes in the lowest bits, so outputs are listed last-to-first
    # Ex: outputs [S0, T0] -> {unit_values, out_T0, out_S0}
    packed = ["unit_values"]
    for index in range(len(plan["outputs"]) - 1, -1, -1):
        packed.append(f"out_{plan['outputs'][index][0]}")
    lines.append(f"    assign observables = {{{', '.join(packed)}}};")
    lines.append("    assign state = fsm_state;")
    lines.append("")
    lines.append("endmodule")

    with open(filename, "w") as file:
        file.write("\n".join(lines) + "\n")

    with open(header_filename, "w") as file:
        file.write("`ifndef GENERATED_CONFIG_VH\n")
        file.write("`define GENERATED_CONFIG_VH\n")
        file.write(f"`define NUM_OBSERVABLES {len(observables)}\n")
        file.write("`endif\n")

    # print the switch and display map for the demo
    print("\nFPGA input map:")
    for name, expression, label in input_wiring:
        print(f"    {name} = {label}")
    print("Display items (display button):")
    for index in range(len(observables)):
        print(f"    {index} = {observables[index]}")
