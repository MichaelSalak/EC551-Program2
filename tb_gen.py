import random
from rtl_gen import WIDTH, select_width

# Testbench generator: writes a self-checking testbench.v
# for each test vector it pulses start, then checks every cycle's FSM state and unit outputs,
# then checks the final outputs. Vector 2 also holds en low to test the step button behavior.
# expected values are computed in Python directly from the SSA equations


# compute every SSA value from the input values (results wrap to WIDTH bits like the hardware)
# Ex: [A0 = B + C], {"B": 2, "C": 3} -> {"B": 2, "C": 3, "A0": 5}
def evaluate(ssa_equations, input_values):
    values = dict(input_values)

    for eq in ssa_equations:
        operands = []
        for operand in (eq["src1"], eq["src2"]):
            if operand.isdigit():
                operands.append(int(operand))
            else:
                operands.append(values[operand])

        if eq["op"] == "+":
            result = operands[0] + operands[1]
        elif eq["op"] == "-":
            result = operands[0] - operands[1]
        else:
            result = operands[0] * operands[1]

        values[eq["dest"]] = result % (1 << WIDTH)

    return values


# parse user input values
# Ex: "B=3,C=5" -> {"B": 3, "C": 5}
def parse_input_string(text):
    values = {}
    if not text:
        return values

    for part in text.split(","):
        name, value = part.split("=")
        values[name.strip()] = int(value)

    return values


# write testbench.v; vector 1 uses the user's values, other inputs are random 1..15 (fits 4 switches)
def write_testbench(plan, dag, ssa_equations, module_name, filename, user_values, num_vectors=3):
    rng = random.Random(551)
    state_bits = select_width(plan["num_cycles"] + 2)

    for name in user_values:
        if name not in dag["inputs"]:
            raise ValueError(f"'{name}' is not a primary input {dag['inputs']}")

    lines = []
    lines.append(f"// testbench.v - generated by tb_gen.py for {module_name}")
    lines.append("`timescale 1ns / 1ps")
    lines.append("module testbench;")
    lines.append("    reg clk = 0, rst = 1, en = 1, start = 0;")
    for name in dag["inputs"]:
        lines.append(f"    reg [{WIDTH-1}:0] in_{name} = 0;")
    for name, reg_name in plan["outputs"]:
        lines.append(f"    wire [{WIDTH-1}:0] out_{name};")
    lines.append(f"    wire [{state_bits-1}:0] state;")
    lines.append("    wire done;")
    lines.append("    integer errors = 0;")
    lines.append("")

    # device under test
    ports = [".clk(clk)", ".rst(rst)", ".en(en)", ".start(start)"]
    for name in dag["inputs"]:
        ports.append(f".in_{name}(in_{name})")
    for name, reg_name in plan["outputs"]:
        ports.append(f".out_{name}(out_{name})")
    ports.append(".state(state)")
    ports.append(".done(done)")
    lines.append(f"    {module_name} dut ({', '.join(ports)});")
    lines.append("")
    lines.append("    always #5 clk = ~clk;")
    lines.append("")

    # check task: print a message and count the error when a value is wrong
    lines.append("    task check;")
    lines.append("        input [8*64-1:0] label;")
    lines.append("        input [31:0] actual;")
    lines.append("        input [31:0] expected;")
    lines.append("        begin")
    lines.append("            if (actual !== expected) begin")
    lines.append('                $display("  FAIL %0s: got %0d, expected %0d", label, actual, expected);')
    lines.append("                errors = errors + 1;")
    lines.append("            end")
    lines.append("        end")
    lines.append("    endtask")
    lines.append("")
    lines.append("    initial begin")
    lines.append("        repeat (2) @(negedge clk);")
    lines.append("        rst = 0;")

    for vector in range(1, num_vectors + 1):
        # pick input values
        values = {}
        for name in dag["inputs"]:
            if vector == 1 and name in user_values:
                values[name] = user_values[name]
            else:
                values[name] = rng.randint(1, 15)
        expected = evaluate(ssa_equations, values)

        value_text = []
        for name in dag["inputs"]:
            value_text.append(f"{name}={values[name]}")

        lines.append("")
        lines.append(f'        $display("Vector {vector}: {" ".join(value_text)}");')
        lines.append("        @(negedge clk);")
        for name in dag["inputs"]:
            lines.append(f"        in_{name} = {values[name]};")
        lines.append("        start = 1;")
        lines.append("        @(negedge clk);")
        lines.append("        start = 0;")

        for cycle in range(1, plan["num_cycles"] + 1):
            lines.append(f'        check("v{vector} state", state, {cycle});')

            for op in plan["states"][cycle]:
                value = expected[op["dest"]]
                lines.append(f'        check("v{vector} c{cycle} {op["text"]}", dut.{op["unit"]}_y, {value});')

            # vector 2: hold en low for 3 clocks, state must not move
            if vector == 2 and cycle == 1:
                lines.append("        en = 0;")
                lines.append("        repeat (3) @(negedge clk);")
                lines.append(f'        check("v{vector} hold with en=0", state, {cycle});')
                lines.append("        en = 1;")

            lines.append("        @(negedge clk);")

        lines.append(f'        check("v{vector} done", done, 1);')
        for name, reg_name in plan["outputs"]:
            lines.append(f'        check("v{vector} out_{name}", out_{name}, {expected[name]});')
            lines.append(f'        $display("  out_{name} = %0d (expected {expected[name]})", out_{name});')

    lines.append("")
    lines.append('        if (errors == 0) $display("PASS");')
    lines.append('        else $display("FAIL: %0d errors", errors);')
    lines.append("        $finish;")
    lines.append("    end")
    lines.append("endmodule")

    with open(filename, "w") as file:
        file.write("\n".join(lines) + "\n")
